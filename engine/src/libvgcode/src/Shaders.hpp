#define BEAD_FRAME_GLSL \
"vec3 bead_normal(float code) {\n" \
"  if (code < 1.0) return vec3(0.0, 0.0, 1.0);\n" \
"  float c = code - 1.0;\n" \
"  float qx = floor(c / 2048.0);\n" \
"  vec2 n = vec2(qx, c - 2048.0 * qx) / 1023.5 - 1.0;\n" \
"  return vec3(n, sqrt(max(0.0, 1.0 - dot(n, n))));\n" \
"}\n" \
"vec3 bead_right(vec3 line_dir, vec3 normal) {\n" \
"  return abs(dot(line_dir, normal)) > 0.9 ? normalize(cross(vec3(1, 0, 0), line_dir)) : normalize(cross(line_dir, normal));\n" \
"}\n" \
"vec2 bead_height_width(vec2 height_width, float code, vec3 right, vec3 normal) {\n" \
"  return code < 1.0 ? height_width : vec2(height_width.x * normal.z, height_width.y / max(length(right.xy), 0.4));\n" \
"}\n"

static const char* Segments_Vertex_Shader =
"#version 150\n"
"#define POINTY_CAPS\n"
"#define FIX_TWISTING\n"
"uniform vec3 light_top_dir;\n"
"const float light_top_diffuse = 0.6 * 0.8;\n"
"const float light_top_specular = 0.6 * 0.25;\n"
"const float light_top_shininess = 20.0;\n"
"const vec3  light_front_dir = vec3(0.6985074, 0.1397015, 0.6985074);\n"
"const float light_front_diffuse = 0.6 * 0.2;\n"
"const float ambient = 0.2;\n"
"const float emission = 0.15;\n"
"uniform mat4 view_matrix;\n"
"uniform mat4 projection_matrix;\n"
"uniform vec3 camera_position;\n"
"uniform samplerBuffer position_tex;\n"
"uniform samplerBuffer height_width_angle_tex;\n"
"uniform samplerBuffer color_tex;\n"
"uniform usamplerBuffer segment_index_tex;\n"
"uniform bool reverse_order;\n"
"uniform int instances_count;\n"
"uniform int first_instance;\n"
"uniform usamplerBuffer lod_segment_tex;\n"
"uniform bool lod;\n"
"uniform bool flip_y;\n"
"uniform vec4 clipping_plane;\n"
"out vec3 color;\n"
"// ORCA: realistic view - the light the shadow map is able to block, kept apart from the\n"
"// ambient and emissive terms in color, which a shadow does not occlude. Their sum is the\n"
"// single lighting term this replaces, so shading is unchanged while shadows are off.\n"
"out vec3 color_direct;\n"
"// ORCA: realistic view - the fragment shader looks the fragment up in the shadow map, which\n"
"// needs its world position and, for the depth bias, its eye space normal.\n"
"out vec3 world_position;\n"
"out vec3 shadow_normal;\n"
"flat out int segment_id;\n"
"out vec3 cut_color_direct;\n"
"uniform ivec2 lit_layers;\n"
"uniform int grey_below_layer;\n"
"uniform float dim_brightness;\n"
"uniform int kept_vertex;\n"
BEAD_FRAME_GLSL
"vec3 decode_color(float color, int id, int layer) {\n"
"  int c = int(round(color));\n"
"  vec3 rgb = vec3((c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF);\n"
"  if (id != kept_vertex && layer != lit_layers.x && layer != lit_layers.y) {\n"
"    if (dim_brightness >= 0.0)\n"
"      rgb = floor(rgb * dim_brightness);\n"
"    else if (layer < grey_below_layer)\n"
"      rgb = vec3(64.0);\n"
"  }\n"
"  float f = 1.0 / 255.0f;\n"
"  return f * rgb;\n"
"}\n"
"float direct_lighting(vec3 eye_position, vec3 eye_normal) {\n"
"  float top_diffuse = light_top_diffuse * max(dot(eye_normal, light_top_dir), 0.0);\n"
"  float front_diffuse = light_front_diffuse * max(dot(eye_normal, light_front_dir), 0.0);\n"
"  float top_specular = light_top_specular * pow(max(dot(-normalize(eye_position), reflect(-light_top_dir, eye_normal)), 0.0), light_top_shininess);\n"
"  return top_diffuse + front_diffuse + top_specular;\n"
"}\n"
"void main() {\n"
"  // One draw takes up to 8192 segments (SegmentTemplate::render()) from first_instance on: the eight corners of a\n"
"  // box each, or, merged far away, the six vertices of a ribbon.\n"
"  int segment = lod ? gl_VertexID / 6 : gl_VertexID >> 3;\n"
"  int vertex_id = lod ? gl_VertexID - 6 * segment : gl_VertexID & 7;\n"
"  int instance = first_instance + (reverse_order ? instances_count - 1 - segment : segment);\n"
"  int id_a;\n"
"  int id_b;\n"
"  if (lod) {\n"
"    uvec2 ids = texelFetch(lod_segment_tex, instance).rg;\n"
"    id_a = int(ids.x);\n"
"    id_b = int(ids.y);\n"
"  } else {\n"
"    id_a = int(texelFetch(segment_index_tex, instance).r);\n"
"    id_b = id_a + 1;\n"
"  }\n"
"  vec3 pos_a = texelFetch(position_tex, id_a).xyz;\n"
"  vec3 pos_b = texelFetch(position_tex, id_b).xyz;\n"
"  vec3 line = pos_b - pos_a;\n"
"  // directions of the line box in world space\n"
"  float line_len = length(line);\n"
"  vec3 line_dir;\n"
"  if (line_len < 1e-4)\n"
"    line_dir = vec3(1.0, 0.0, 0.0);\n"
"  else\n"
"    line_dir = line / line_len;\n"
"  // For vertical lines, the width and height should be same, there is no concept of up and down.\n"
"  // For simplicity, bead_right() expands width in the x axis, and height in the y axis\n"
"  vec4 hwa_a = texelFetch(height_width_angle_tex, id_a);\n"
"  vec4 hwa_b = texelFetch(height_width_angle_tex, id_b);\n"
"  vec3 bead_up = normalize(bead_normal(hwa_a.w) + bead_normal(hwa_b.w));\n"
"  vec3 line_right_dir = bead_right(line_dir, bead_up);\n"
"  vec3 line_up_dir = normalize(cross(line_right_dir, line_dir));\n"
"  if (lod) {\n"
"    // A bead a pixel or two wide: a ribbon facing the eye, as wide as the bead's section seen from there, lit as the\n"
"    // box's section: along the sides at its edges, toward the eye along its axis. Three vertices across each end.\n"
"    int lod_id = vertex_id < 3 ? id_a : id_b;\n"
"    vec3 lod_endpoint = vertex_id < 3 ? pos_a : pos_b;\n"
"    vec4 lod_hwa = vertex_id < 3 ? hwa_a : hwa_b;\n"
"    vec2 lod_height_width = bead_height_width(lod_hwa.xy, lod_hwa.w, line_right_dir, bead_up);\n"
"    vec3 to_eye = camera_position - lod_endpoint;\n"
"    vec3 facing = to_eye - dot(to_eye, line_dir) * line_dir;\n"
"    facing = dot(facing, facing) < 1e-12 ? line_up_dir : normalize(facing);\n"
"    vec3 side = cross(line_dir, facing);\n"
"    float half_extent = 0.5 * (lod_height_width.y * abs(dot(line_right_dir, side)) + lod_height_width.x * abs(dot(line_up_dir, side)));\n"
"    float lod_side = float(vertex_id - 3 * (vertex_id / 3)) - 1.0;\n"
"    vec3 lod_pos = lod_endpoint + lod_side * half_extent * side;\n"
"    vec3 lod_eye_position = (view_matrix * vec4(lod_pos, 1.0)).xyz;\n"
"    lod_eye_position.z += lod_hwa.w < 1.0 ? lod_hwa.w : 0.0;\n"
"    vec3 lod_eye_normal = mat3(view_matrix) * (lod_side == 0.0 ? facing : lod_side * side);\n"
"    vec3 lod_color = decode_color(texelFetch(color_tex, lod_id).r, lod_id, int(texelFetch(position_tex, lod_id).w));\n"
"    color = lod_color * (ambient + emission);\n"
"    color_direct = lod_color * direct_lighting(lod_eye_position, lod_eye_normal);\n"
"    world_position = lod_pos;\n"
"    shadow_normal = lod_eye_normal;\n"
"    segment_id = id_a;\n"
"    cut_color_direct = clipping_plane.xyz == vec3(0.0) ? vec3(0.0) :\n"
"      lod_color * direct_lighting(lod_eye_position, mat3(view_matrix) * -clipping_plane.xyz);\n"
"    gl_Position = projection_matrix * vec4(lod_eye_position, 1.0);\n"
"    if (flip_y)\n"
"      gl_Position.y = -gl_Position.y;\n"
"    return;\n"
"  }\n"
"  const vec2 horizontal_vertical_view_signs_array[16] = vec2[](\n"
"    //horizontal view (from right)\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(0.0, 0.0),\n"
"    vec2(0.0, -1.0),\n"
"    vec2(0.0, -1.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(0.0, 0.0),\n"
"    // vertical view (from top)\n"
"    vec2(0.0, 1.0),\n"
"    vec2(-1.0, 0.0),\n"
"    vec2(0.0, 0.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(-1.0, 0.0),\n"
"    vec2(0.0, 0.0)\n"
"    );\n"
"  int id = vertex_id < 4 ? id_a : id_b;\n"
"  vec3 endpoint_pos = vertex_id < 4 ? pos_a : pos_b;\n"
"  vec4 hwa = vertex_id < 4 ? hwa_a : hwa_b;\n"
"  vec3 height_width_angle = vec3(bead_height_width(hwa.xy, hwa.w, line_right_dir, bead_up), hwa.z);\n"
"  // ORCA: Extract bias from w component\n"
"  float bias = hwa.w < 1.0 ? hwa.w : 0.0;\n"
"#ifdef FIX_TWISTING\n"
"  int closer_id = (dot(camera_position - pos_a, camera_position - pos_a) < dot(camera_position - pos_b, camera_position - pos_b)) ? id_a : id_b;\n"
"  vec3 closer_pos = (closer_id == id_a) ? pos_a : pos_b;\n"
"  vec3 camera_view_dir = normalize(closer_pos - camera_position);\n"
"  vec4 closer_hwa = (closer_id == id_a) ? hwa_a : hwa_b;\n"
"  vec3 closer_height_width_angle = vec3(bead_height_width(closer_hwa.xy, closer_hwa.w, line_right_dir, bead_up), closer_hwa.z);\n"
"  vec3 diagonal_dir_border = normalize(closer_height_width_angle.x * line_up_dir + closer_height_width_angle.y * line_right_dir);\n"
"#else\n"
"  vec3 camera_view_dir = normalize(endpoint_pos - camera_position);\n"
"  vec3 diagonal_dir_border = normalize(height_width_angle.x * line_up_dir + height_width_angle.y * line_right_dir);\n"
"#endif\n"
"  bool is_vertical_view = abs(dot(camera_view_dir, line_up_dir)) / abs(dot(diagonal_dir_border, line_up_dir)) >\n"
"    abs(dot(camera_view_dir, line_right_dir)) / abs(dot(diagonal_dir_border, line_right_dir));\n"
"  vec2 signs = horizontal_vertical_view_signs_array[vertex_id + 8 * int(is_vertical_view)];\n"
"#ifndef POINTY_CAPS\n"
"  if (vertex_id == 2 || vertex_id == 7) signs = -horizontal_vertical_view_signs_array[(vertex_id - 2) + 8 * int(is_vertical_view)];\n"
"#endif\n"
"  float view_right_sign = sign(dot(-camera_view_dir, line_right_dir));\n"
"  float view_top_sign = sign(dot(-camera_view_dir, line_up_dir));\n"
"  float half_height = 0.5 * height_width_angle.x;\n"
"  float half_width = 0.5 * height_width_angle.y;\n"
"  vec3 horizontal_dir = half_width * line_right_dir;\n"
"  vec3 vertical_dir = half_height * line_up_dir;\n"
"  float horizontal_sign = signs.x * view_right_sign;\n"
"  float vertical_sign = signs.y * view_top_sign;\n"
"  vec3 pos = endpoint_pos + horizontal_sign * horizontal_dir + vertical_sign * vertical_dir;\n"
"  if (vertex_id == 2 || vertex_id == 7) {\n"
"    float line_dir_sign = (vertex_id == 2) ? -1.0 : 1.0;\n"
"    if (height_width_angle.z == 0) {\n"
"#ifdef POINTY_CAPS\n"
"      // There I add a cap to lines that do not have a following line\n"
"      // (or they have one, but perfectly aligned, so the cap is hidden inside the next line).\n"
"      pos += line_dir_sign * line_dir * half_width;\n"
"#endif\n"
"    }\n"
"    else {\n"
"      pos += line_dir_sign * line_dir * half_width * sin(abs(height_width_angle.z) * 0.5);\n"
"      pos += sign(height_width_angle.z) * horizontal_dir * cos(abs(height_width_angle.z) * 0.5);\n"
"    }\n"
"  }\n"
"  vec3 eye_position = (view_matrix * vec4(pos, 1.0)).xyz;\n"
"  // ORCA: Apply bias to z-position to avoid z-fighting\n"
"  eye_position.z += bias;\n"
"  vec3 eye_normal = (view_matrix * vec4(normalize(pos - endpoint_pos), 0.0)).xyz;\n"
"  vec3 color_base = decode_color(texelFetch(color_tex, id).r, id, int(texelFetch(position_tex, id).w));\n"
"  color = color_base * (ambient + emission);\n"
"  color_direct = color_base * direct_lighting(eye_position, eye_normal);\n"
"  world_position = pos;\n"
"  shadow_normal = eye_normal;\n"
"  segment_id = id_a;\n"
"  cut_color_direct = clipping_plane.xyz == vec3(0.0) ? vec3(0.0) :\n"
"    color_base * direct_lighting(eye_position, mat3(view_matrix) * -clipping_plane.xyz);\n"
"  gl_Position = projection_matrix * vec4(eye_position, 1.0);\n""  if (flip_y)\n"
"    gl_Position.y = -gl_Position.y;\n"
"}\n";

